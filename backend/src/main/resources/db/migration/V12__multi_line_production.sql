CREATE TABLE production_order_lines (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES production_orders(id),
 line_number INTEGER NOT NULL,
 bom_id BIGINT NOT NULL REFERENCES bom_versions(id),
 quantity INTEGER NOT NULL CHECK(quantity>0),
 color VARCHAR(60) NOT NULL,
 UNIQUE(order_id,line_number)
);
CREATE TABLE production_line_materials (
 line_id BIGINT NOT NULL REFERENCES production_order_lines(id),
 part_id BIGINT NOT NULL REFERENCES parts(id),
 quantity DECIMAL(18,3) NOT NULL CHECK(quantity>0),
 PRIMARY KEY(line_id,part_id)
);
INSERT INTO production_order_lines(order_id,line_number,bom_id,quantity,color)
 SELECT id,1,bom_id,quantity,color FROM production_orders;
INSERT INTO production_line_materials(line_id,part_id,quantity)
 SELECT l.id,m.part_id,m.quantity FROM production_order_lines l JOIN production_materials m ON m.order_id=l.order_id;
ALTER TABLE vehicles ADD production_line_id BIGINT REFERENCES production_order_lines(id);
UPDATE vehicles SET production_line_id=(SELECT id FROM production_order_lines l WHERE l.order_id=vehicles.order_id AND line_number=1) WHERE order_id IS NOT NULL;
