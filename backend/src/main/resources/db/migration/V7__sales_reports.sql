CREATE TABLE revenue_sales (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_type VARCHAR(10) NOT NULL CHECK(source_type IN ('VEHICLE','PART')),
 source_id BIGINT NOT NULL,
 channel VARCHAR(10) NOT NULL CHECK(channel IN ('STORE','DEALER')),
 party_code VARCHAR(80) NOT NULL, party_name VARCHAR(200) NOT NULL,
 phone VARCHAR(100) NOT NULL DEFAULT '', province VARCHAR(200) NOT NULL DEFAULT '',
 sale_date DATE NOT NULL, deleted BOOLEAN NOT NULL DEFAULT FALSE,
 created_by BIGINT NOT NULL REFERENCES app_users(id),
 UNIQUE(source_type,source_id)
);
CREATE TABLE revenue_lines (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sale_id BIGINT NOT NULL REFERENCES revenue_sales(id),
 members VARCHAR(12000) NOT NULL,
 item_code VARCHAR(100) NOT NULL, item_name VARCHAR(500) NOT NULL,
 category VARCHAR(2) NOT NULL CHECK(category IN ('TM','DK','LK')),
 quantity DECIMAL(18,3) NOT NULL CHECK(quantity>0),
 unit_price DECIMAL(18,2) NOT NULL CHECK(unit_price>=0),
 factory_unit_cost DECIMAL(18,2) CHECK(factory_unit_cost>=0),
 discount DECIMAL(18,2) NOT NULL DEFAULT 0 CHECK(discount>=0),
 support DECIMAL(18,2) NOT NULL DEFAULT 0 CHECK(support>=0)
);
CREATE TABLE revenue_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sale_id BIGINT NOT NULL REFERENCES revenue_sales(id),
 kind VARCHAR(10) NOT NULL CHECK(kind IN ('PAYMENT','CSKH')),
 entry_date DATE NOT NULL, amount DECIMAL(18,2) NOT NULL CHECK(amount>0),
 note VARCHAR(500) NOT NULL, deleted BOOLEAN NOT NULL DEFAULT FALSE,
 created_by BIGINT NOT NULL REFERENCES app_users(id), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX revenue_sales_date_idx ON revenue_sales(sale_date,channel);
CREATE INDEX revenue_entries_sale_idx ON revenue_entries(sale_id,deleted);
